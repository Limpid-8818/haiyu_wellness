export const sqliteAssistantRunsSchema = `
ALTER TABLE assistant_sessions ADD COLUMN mode TEXT NOT NULL DEFAULT 'safe_guidance';
ALTER TABLE assistant_sessions ADD COLUMN model_name TEXT;
CREATE TABLE IF NOT EXISTS agent_runs (
  id TEXT PRIMARY KEY,
  session_id TEXT NOT NULL REFERENCES assistant_sessions(id) ON DELETE CASCADE,
  actor_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  assistant_role TEXT NOT NULL CHECK (assistant_role IN ('public','guest','staff','dean')),
  client_request_id TEXT NOT NULL,
  intent_category TEXT NOT NULL DEFAULT 'general',
  clarification_count INTEGER NOT NULL DEFAULT 0,
  clarification_state_json TEXT NOT NULL DEFAULT '{}',
  status TEXT NOT NULL CHECK (status IN ('queued','running','completed','failed','interrupted')),
  input_text TEXT NOT NULL,
  output_text TEXT,
  model_name TEXT,
  provider TEXT,
  is_live INTEGER NOT NULL DEFAULT 0 CHECK (is_live IN (0,1)),
  input_tokens INTEGER NOT NULL DEFAULT 0,
  output_tokens INTEGER NOT NULL DEFAULT 0,
  estimated_cost_usd REAL NOT NULL DEFAULT 0,
  error_code TEXT,
  stop_reason TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  completed_at TEXT,
  UNIQUE (session_id, client_request_id)
);
CREATE INDEX IF NOT EXISTS idx_agent_runs_session_created ON agent_runs(session_id, created_at DESC, id);
CREATE INDEX IF NOT EXISTS idx_agent_runs_status_created ON agent_runs(status, created_at);
CREATE TABLE IF NOT EXISTS agent_steps (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  run_id TEXT NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
  step_index INTEGER NOT NULL,
  step_type TEXT NOT NULL CHECK (step_type IN ('model','tool','clarification','final')),
  status TEXT NOT NULL CHECK (status IN ('running','completed','failed','reused')),
  summary TEXT NOT NULL DEFAULT '',
  source_json TEXT NOT NULL DEFAULT '[]',
  diagnostic_json TEXT NOT NULL DEFAULT '{}',
  input_tokens INTEGER NOT NULL DEFAULT 0,
  output_tokens INTEGER NOT NULL DEFAULT 0,
  estimated_cost_usd REAL NOT NULL DEFAULT 0,
  error_code TEXT,
  started_at TEXT NOT NULL,
  completed_at TEXT,
  duration_ms INTEGER,
  UNIQUE (run_id, step_index)
);
CREATE INDEX IF NOT EXISTS idx_agent_steps_run ON agent_steps(run_id, step_index);
CREATE TABLE IF NOT EXISTS tool_executions (
  id TEXT PRIMARY KEY,
  run_id TEXT NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
  step_id INTEGER REFERENCES agent_steps(id) ON DELETE SET NULL,
  tool_name TEXT NOT NULL,
  tool_call_id TEXT NOT NULL,
  idempotency_key TEXT NOT NULL,
  arguments_json TEXT NOT NULL,
  result_json TEXT NOT NULL,
  source_json TEXT NOT NULL DEFAULT '[]',
  status TEXT NOT NULL CHECK (status IN ('completed','failed','reused')),
  error_code TEXT,
  started_at TEXT NOT NULL,
  completed_at TEXT NOT NULL,
  duration_ms INTEGER NOT NULL DEFAULT 0,
  UNIQUE (run_id, idempotency_key),
  UNIQUE (run_id, tool_call_id)
);
CREATE INDEX IF NOT EXISTS idx_tool_executions_run ON tool_executions(run_id, started_at);
`;

