export function questsForStage(stage) { return selectQuestsForStage(stage, Object.keys(quests)); }

export function terminalQuestsForRange(firstStage, lastStage) {
  return Object.keys(quests).filter(id => {
    const stage = Number(id.match(/^Q(\d+)\./)?.[1]);
    return Number.isInteger(stage) && stage >= firstStage && stage <= lastStage;
  });
}

export async function runRegisteredQuest(questId, context = {}) {
  const moduleUrl = quests[questId];
  if (!moduleUrl) throw new Error(`Unknown registered quest: ${questId}`);
  const { run } = await import(moduleUrl);
  return await run({ questId, ...context });
}
