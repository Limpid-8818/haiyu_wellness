async (page) => {
  const cfg = __CONFIG__;
  page.setDefaultTimeout(5000);
  const evidence = { assertions: [], http: [], objects: {}, pageErrors: [], screenshots: [] };
  page.on('pageerror', error => evidence.pageErrors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  const check = (value, label) => { if (!value) throw new Error(label); evidence.assertions.push(label); };
  const visible = async (label, needle) => { const text = await page.locator('body').innerText(); check(text.includes(needle), label); return text; };
  const snap = async (name, selector) => { const target = `${cfg.out}/${name}.png`; if (selector) await page.locator(selector).first().screenshot({ path: target }); else await page.screenshot({ path: target, fullPage: false }); evidence.screenshots.push(target); };
  const login = async (role, username) => {
    if (await page.getByRole('button', { name: '退出登录', exact: true }).count()) await page.getByRole('button', { name: '退出登录', exact: true }).click();
    await page.getByRole('button', { name: role === 'guest' ? /^我是客人/ : /^我是工作人员/ }).first().click();
    await page.getByLabel('账号', { exact: true }).fill(username);
    await page.getByLabel('密码', { exact: true }).fill('Synthetic-stage1-only-123');
    await page.getByRole('button', { name: '进入工作区　→', exact: true }).click();
    await page.locator('.side-nav').waitFor();
  };
  const api = async (username, role, route, method = 'GET', body, expected = 200) => {
    const result = await page.evaluate(async ({ username, role, route, method, body }) => {
      const auth = await fetch('/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username, role, password: 'Synthetic-stage1-only-123' }) });
      const login = await auth.json();
      const response = await fetch('/api' + route, { method, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${login.token}` }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
      return { status: response.status, data: await response.json() };
    }, { username, role, route, method, body });
    evidence.http.push({ username, route, method, status: result.status, code: result.data.code || null });
    check(result.status === expected, `${method} ${route} HTTP${expected}`); return result.data;
  };
  const meals = async () => { await page.locator('.side-nav').getByRole('button', { name: '膳食', exact: true }).click(); await page.getByRole('heading', { name: '每日膳食', exact: true }).waitFor(); };
  const refreshMeals = async () => { await page.locator('.page-title').getByRole('button', { name: '刷新　↻', exact: true }).click(); await page.locator('.meal-day-grid').waitFor(); };
  await page.goto(cfg.web);
  await login('guest', 'stage1_mixed');
  await page.locator('.side-nav').getByRole('button', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: /我的档案/ }).click();
  await page.locator('.health-verified-grid').waitFor();
  await page.getByRole('button', { name: '刷新档案　↻', exact: true }).click();
  await page.locator('.health-verified-grid').waitFor();
  const summary = await page.locator('.form-surface input[readonly]').evaluateAll(rows => rows.map(row => row.value).join('；'));
  check(summary.includes('高血压') && summary.includes('海鲜、空气') && !summary.includes('暂无记录'), 'F03 上方正式摘要一致');
  check((await page.locator('.health-verified-panel').innerText()).includes('海鲜、空气'), 'F03 下方正式档案一致');
  await snap('01-formal-summary');
  await login('guest', 'stage1_mixed');
  await meals();
  await page.getByRole('button', { name: '生成此日期餐单', exact: true }).click();
  await page.locator('.meal-day-grid').waitFor();
  const blocked = await api('stage1_mixed', 'guest', `/meals/menu?date=${cfg.date}`);
  check(blocked.items.length === 9 && blocked.items.every(item => !item.dish && !item.eligibleReplacements.length), 'F01 未核对的未知项暂停九餐位');
  await page.getByRole('button', { name: '转交负责医护核对', exact: true }).click();
  await page.getByText('处理状态：待医护核对', { exact: false }).waitFor();
  await snap('02-mixed-pending');
  await login('staff', 'stage1_clinician');
  await page.locator('.side-nav').getByRole('button', { name: /客人/ }).click();
  await page.locator('.guest-row').filter({ hasText: '合成限制核对客人' }).click();
  await page.locator('.meal-restriction-review').waitFor();
  const staffSummary = await page.locator('.health-alert').allTextContents();
  check(staffSummary.join(' ').includes('高血压') && staffSummary.join(' ').includes('海鲜、空气'), 'F03 医护客人详情正式摘要一致');
  await page.getByLabel('“空气”的分类').selectOption('non_food');
  await page.getByLabel('人工核对依据', { exact: true }).fill('合成客人与医护明确核对空气为环境描述，保留原始记录；海鲜及鸡蛋继续作为食物限制。');
  await page.getByRole('button', { name: '保存医护分类核对', exact: true }).click();
  await page.getByText('处理状态：已人工核对', { exact: false }).waitFor();
  await snap('03-clinician-classified');
  await login('guest', 'stage1_mixed');
  await meals(); await page.locator('.meal-day-grid').waitFor();
  for (let index = 0; index < 9; index++) {
    const items = page.locator('.meal-item'); const item = items.nth(index);
    await item.getByRole('button', { name: '替换此餐位', exact: true }).click();
    await item.getByLabel('替换菜品').waitFor();
    const options = await item.getByLabel('替换菜品').locator('option').evaluateAll(rows => rows.map(row => row.value).filter(Boolean));
    check(options.length > 0, `F01 第${index + 1}餐位恢复合规选项`);
    await item.getByLabel('替换菜品').selectOption(options[0]);
    await item.getByLabel('替换原因', { exact: true }).fill('医护人工核对后补齐合规食物');
    await item.getByRole('button', { name: '确认替换', exact: true }).click();
    await page.locator('.meal-day-grid').waitFor();
    await page.waitForFunction(() => !document.querySelector('.meal-swap-form'));
  }
  const restored = await api('stage1_mixed', 'guest', `/meals/menu?date=${cfg.date}`);
  check(restored.status === 'ready' && restored.items.every(item => item.dish && !item.currentlyRestricted), 'F01 九餐位恢复且限制仍有效');
  const original = await api('stage1_mixed', 'guest', '/me/health-profile');
  check(original.verifiedProfile.allergies.items.join('、') === '海鲜、空气', 'F01 原始正式过敏未删除');
  await snap('04-mixed-restored');
  evidence.objects.mixed = { guestId: 'stage1_mixed', menuId: restored.menu.id, profileVersion: original.profileVersion, review: restored.currentRuleBasis.restrictionReview, rawAllergies: original.verifiedProfile.allergies };
  await login('guest', 'stage1_order'); await meals();
  await page.getByRole('button', { name: '生成此日期餐单', exact: true }).click(); await page.locator('.meal-day-grid').waitFor();
  await page.getByRole('button', { name: '提交早餐订单', exact: true }).click();
  await page.locator('.meal-order-status').waitFor();
  const ordered = (await api('stage1_order', 'guest', `/meals/orders?date=${cfg.date}`))[0];
  const pending = await api('stage1_order', 'guest', '/me/health-intakes', 'POST', { baseProfileVersion: 1,
    profile: { allergies: { status: 'reported', items: ['海鲜'] }, dietaryRestrictions: { status: 'reported', items: ['鸡蛋'] } } }, 201);
  await refreshMeals();
  await visible('F02 客人订单已暂停', '须复核 · 暂停推进');
  const currentText = await page.locator('.meal-avoidance').innerText();
  check(currentText.includes('生成时未列出明确限制；这是历史快照。') && currentText.includes('海鲜') && currentText.includes('鸡蛋'), 'F11 当前限制与旧空快照明确区分');
  await snap('05-order-paused-current-vs-generated', '.meal-avoidance');
  await snap('05b-guest-order-paused', '.meal-order-status');
  await api('stage1_dietitian', 'staff', `/staff/meals/orders/${ordered.id}/status`, 'PATCH', { status: 'preparing' }, 409);
  await login('staff', 'stage1_dietitian');
  await page.getByRole('heading', { name: '备餐订单', exact: true }).waitFor();
  await visible('F02 配餐台显示同样暂停结论', '须复核 · 暂停推进');
  check(await page.getByRole('button', { name: '开始备餐', exact: true }).isDisabled(), 'F02 配餐台推进按钮停用');
  await snap('06-dietitian-paused');
  await api('stage1_clinician', 'staff', `/staff/health-intakes/${pending.pendingIntakes[0].id}/confirm`, 'POST', { baseProfileVersion: 1 });
  await api('stage1_dietitian', 'staff', `/staff/meals/orders/${ordered.id}/status`, 'PATCH', { status: 'preparing' }, 409);
  await login('guest', 'stage1_order'); await meals(); await page.locator('.meal-day-grid').waitFor();
  let menu = await api('stage1_order', 'guest', `/meals/menu?date=${cfg.date}`);
  for (const old of menu.items.filter(item => item.mealType === 'breakfast' && item.currentlyRestricted)) {
    const index = menu.items.findIndex(item => item.id === old.id); const item = page.locator('.meal-item').nth(index);
    await item.getByRole('button', { name: '替换此餐位', exact: true }).click();
    await item.getByLabel('替换菜品').waitFor();
    const options = await item.getByLabel('替换菜品').locator('option').evaluateAll(rows => rows.map(row => row.value).filter(Boolean));
    await item.getByLabel('替换菜品').selectOption(options[0]);
    await item.getByLabel('替换原因', { exact: true }).fill('新增鸡蛋与海鲜限制后替换订单冲突菜品');
    await item.getByRole('button', { name: '确认替换', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.meal-swap-form')); await page.locator('.meal-day-grid').waitFor();
  }
  await api('stage1_dietitian', 'staff', `/staff/meals/orders/${ordered.id}/status`, 'PATCH', { status: 'preparing' }, 409);
  await login('staff', 'stage1_dietitian');
  await page.getByRole('heading', { name: '备餐订单', exact: true }).waitFor();
  await page.getByLabel('订单复核说明', { exact: true }).fill('合成负责配餐员核对当前海鲜/鸡蛋限制与三餐位均符合，恢复备餐。');
  await page.getByRole('button', { name: '确认当前订单符合限制', exact: true }).click();
  await page.getByRole('button', { name: '开始备餐', exact: true }).waitFor();
  await page.getByRole('button', { name: '开始备餐', exact: true }).click();
  await page.getByRole('button', { name: '标记已送达', exact: true }).waitFor(); await snap('07-dietitian-preparing');
  const repeat = await api('stage1_dietitian', 'staff', `/staff/meals/orders/${ordered.id}/status`, 'PATCH', { status: 'preparing' });
  check(repeat.changed === false, 'F02 重复推进不重复写');
  await login('guest', 'stage1_order'); await meals(); await page.locator('.meal-order-status').waitFor();
  const readBack = (await api('stage1_order', 'guest', `/meals/orders?date=${cfg.date}`))[0];
  const staffBack = (await api('stage1_dietitian', 'staff', `/staff/meals/orders?date=${cfg.date}&mealType=breakfast`))[0];
  check(readBack.id === ordered.id && readBack.status === 'preparing' && !readBack.reviewRequired && JSON.stringify(readBack.dishes) === JSON.stringify(staffBack.dishes), 'F02 同一订单双方回读备餐与菜品一致');
  await visible('F02 客人可见恢复备餐', '备餐中'); await snap('08-guest-preparing-readback', '.meal-order-status');
  evidence.objects.order = readBack;
  check(evidence.pageErrors.length === 0, '网页运行错误0');
  console.log('STAGE1_BROWSER_RESULT:' + JSON.stringify(evidence));
  return evidence;
}
